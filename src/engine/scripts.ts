export function workWindow(need: number): number {
  return need * 3 + 6
}

function inferRole(kind: string): RoleTier {
  if (/女主/.test(kind)) return 'lead'
  if (/女二/.test(kind)) return 'second'
  if (/女三/.test(kind)) return 'third'
  if (/客串/.test(kind)) return 'cameo'
  return 'support'
}

function inferHype(s: { grade: ScriptGrade; tags?: string[]; type: string }): ScriptHype {
  if (s.tags?.some((t) => /大 IP/.test(t))) return 'ip'
  if (s.grade === 'S' && /电影/.test(s.type)) return 'award'
  if (s.grade === 'S' || s.grade === 'A') return 'trade'
  return 'quiet'
}

function S(
  s: Omit<ScriptDef, 'tags' | 'deposit' | 'promoNeed' | 'promoDays' | 'track' | 'deadlineDays' | 'roleTier' | 'hype' | 'awardTrack' | 'press' | 'fromYear'> & {
    tags?: string[]
    deposit?: number
    promoNeed?: number
    promoDays?: number
    deadlineDays?: number
    track?: Track
    roleTier?: RoleTier
    hype?: ScriptHype
    awardTrack?: boolean
    press?: string[]
    fromYear?: number
  },
): ScriptDef {
  const promoNeed = s.promoNeed ?? 2
  const roleTier = s.roleTier ?? inferRole(s.roleKind)
  const hype = s.hype ?? inferHype(s)
  return {
    ...s,
    track: s.track ?? 'film',
    tags: s.tags ?? [s.type],
    press: s.press ?? [],
    fromYear: s.fromYear ?? 1,
    deposit: s.deposit ?? Math.round(s.pay * 0.2),
    promoNeed,
    deadlineDays: s.deadlineDays ?? workWindow(s.shootNeed),
    promoDays: s.promoDays ?? workWindow(promoNeed),
    roleTier,
    hype,
    awardTrack: s.awardTrack ?? false,
  }
}

