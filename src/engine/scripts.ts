export function monthIndex(week: number): number {
  return Math.floor((week - 1) / 4)
}

function mulberry32(a: number) {
  return () => {
    let t = (a += 0x6d2b79f5)
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function gradeOpen(script: ScriptDef, recognition: number, fans: number, identity: IdentityId): boolean {
  return gradeUnlocked(script.grade, recognition, fans, identity)
}

export type OfferAccess = {
  flags?: Record<string, boolean>
  favor?: Record<string, number>
  met?: Record<string, boolean>
}

function scriptUnlocked(script: ScriptDef, access?: OfferAccess): boolean {
  if (!script.unlock) return true
  const flags = access?.flags ?? {}
  const favor = access?.favor ?? {}
  const met = access?.met ?? {}
  if (script.unlock === 'broker') return Boolean(flags.brokerSpecial)
  if (script.unlock === 'liangshi') return Boolean(met.liangshi) && (favor.liangshi ?? 0) >= (script.unlockFavor ?? 50)
  if (script.unlock === 'guyan') return Boolean(met.guyan) && (favor.guyan ?? 0) >= (script.unlockFavor ?? 55)
  return false
}

export function monthOfferIds(
  seed: number,
  week: number,
  finished: string[],
  filmingIds: string[],
  recognition: number,
  identity: IdentityId,
  track: Track = 'film',
  fans = 0,
  access?: OfferAccess,
): string[] {
  const m = monthIndex(week)
  const year = playYear(week)
  const rng = mulberry32((seed + (m + 1) * 1315423911 + (track === 'music' ? 17 : track === 'variety' ? 31 : 0)) >>> 0)
  const blocked = new Set([...finished, ...filmingIds])
  const pool = SCRIPTS.filter((s) => {
    if (s.track !== track || blocked.has(s.id) || !scriptUnlocked(s, access)) return false
    if ((s.fromYear ?? 1) > year) return false
    if (year >= 2 && s.grade === 'C') return false
    if (!gradeOpen(s, recognition, fans, identity)) return false
    if (s.roleTier === 'lead' && s.awardTrack && (s.hype === 'award' || /电影/.test(s.type))) {
      if (year < 3 && (recognition < 80 || fans < 60000)) return false
      if (year >= 3 && (recognition < 80 || fans < 90000)) return false
    }
    if (s.unlock) return true
    return roleOffered(s.roleTier, recognition, fans, year)
  })
  const specials = pool.filter((s) => s.unlock)
  const regular = pool.filter((s) => !s.unlock)
  const staples = regular.filter((s) => !s.random)
  const extras = regular.filter((s) => s.random && rng() > 0.42)
  let cand = [...staples, ...extras]
  if (cand.length < 3) cand = regular
  if (year >= 2) {
    const now = cand.filter((s) => (s.fromYear ?? 1) === year)
    const older = cand.filter((s) => (s.fromYear ?? 1) < year)
    cand = now.length >= 3 ? now : [...now, ...older]
  }
  const shuffled = [...cand]
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }
  const forced = [...specials]
  for (let i = forced.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[forced[i], forced[j]] = [forced[j], forced[i]]
  }
  const pickSpecial = forced.slice(0, 2)
  const need = Math.max(0, 3 - pickSpecial.length)
  const ids = [...pickSpecial, ...shuffled.filter((s) => !pickSpecial.includes(s)).slice(0, need)].map((s) => s.id)
  return ids.slice(0, 3)
}

export function monthOffers(week: number, finished: string[], filmingId: string | null): ScriptDef[] {
  return monthOfferIds(1, week, finished, filmingId ? [filmingId] : [], 0, 'college')
    .map((id) => scriptById(id))
    .filter((s): s is ScriptDef => Boolean(s))
}
