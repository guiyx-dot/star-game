export function roleLine(script: ScriptDef): string {
  if (script.track === 'music') {
    if (script.roleTier === 'second') return '独唱。有名字。'
    return '声音。不一定有名字。'
  }
  if (script.track === 'variety') return script.roleKind
  if (script.roleTier === 'lead') return '女主'
  if (script.roleTier === 'second') return '女二'
  if (script.roleTier === 'third') return '女三'
  if (script.roleTier === 'cameo') return '客串'
  return '配角'
}

