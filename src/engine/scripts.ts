export function scriptById(id: string): ScriptDef | undefined {
  return SCRIPTS.find((s) => s.id === id)
}

export function rumorLine(script: ScriptDef, week = 1): string {
  if (script.press.length) {
    return script.press[(week + script.id.length) % script.press.length]
  }
  return `《${script.title}》还在选${roleLine(script)}。${script.director}还没点头。`
}

export function scriptMatch(attrs: Attrs, script: ScriptDef): number {
  let num = 0
  let den = 0
  for (const k of ATTR_KEYS) {
    const need = script.need[k]
    if (!need) continue
    const w = script.weights[k] ?? 1
    num += Math.min(1.25, attrs[k] / need) * w
    den += w
  }
  return den ? Math.min(100, Math.round((100 * num) / den)) : 50
}

export function matchWord(n: number): string {
  if (n >= 82) return '倒像你'
  if (n >= 64) return '能试试'
  if (n >= 48) return '有点勉强'
  return '现在不像'
}

export function canTakeScript(
  attrs: Attrs,
  script: ScriptDef,
  career?: { recognition: number; fans: number },
): boolean {
  if (!ATTR_KEYS.every((k) => (script.need[k] ?? 0) <= attrs[k])) return false
  if (script.awardTrack) {
    if (script.roleTier === 'lead') {
      if ((career?.recognition ?? 0) < 80) return false
      if ((career?.fans ?? 0) < 60000) return false
    } else {
      if ((career?.recognition ?? 0) < 32) return false
      if ((career?.fans ?? 0) < 20000) return false
    }
  }
  return true
}

