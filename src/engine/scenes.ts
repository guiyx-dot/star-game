export function companyTalk(booked = 0, track: 'film' | 'music' | 'variety' = 'film'): string {
  if (track === 'music') {
    const extra =
      booked >= 3
        ? '企划摘下耳机说：「你现在的档期排不进录音。小样可以先听，合同今天不能签。」'
        : '企划把几份小样发到平板上：「这个月在找人的歌都在这里。听完挑一首，想试的话我让录音师准备。」'
    return `前台给你拿了鞋套。走廊两边都是录音棚，门一关，外面的声音立刻小了。\n\n${extra}`
  }
  if (track === 'variety') {
    const extra =
      booked >= 3
        ? '导播查完档期，摇了摇头：「你现在排得太满，飞行录制容易撞。环节可以看，先别签。」'
        : '导播把几份环节单递过来：「这个月空出来的位置都在这儿。有兴趣就试一段，合适再谈录制时间。」'
    return `候播室里有人对着提词器彩排。工作人员把你带到空会议室，顺手关上门。\n\n${extra}`
  }
  const extra =
    booked >= 3
      ? '周衡看完你的日程说：「三部戏同时拍已经够乱了。你可以先看本，但今天不能再签。等有一部杀青再说。」'
      : '周衡把通告按类型分开：「这个月在找人的都在这儿。今天最多试一部，先看清楚角色和工期，别只盯着片酬。」'
  return `前台把几份通告送进会议室。周衡拉开你旁边的椅子，示意你坐。

${extra}`
}

