function gapTalk(attrs: Attrs, script: ScriptDef): string {
  const gaps = needGaps(attrs, script).filter((g) => g.have < g.need)
  if (!gaps.length) return '整体没什么硬伤'
  const names = gaps.map((g) => NEED_NAME[g.key])
  if (names.length === 1) return `${names[0]}这一项还撑不住镜头`
  return `${names.join('、')}都差了一点`
}

